package io.springgraph.intellij.analysis;

import java.nio.file.Path;
import java.util.List;

/**
 * One {@code javac -proc:only} run over a module's main sources: annotation processing only, no class files. Built from
 * the IntelliJ project model by {@link ModuleAnalysisPlanner}; plain data, so {@link JavacRunner} is testable without
 * the IDE.
 *
 * @param javac         the module JDK's javac executable
 * @param sources       the module's main {@code .java} files
 * @param classpath     compile classpath (libraries and the outputs of modules it depends on)
 * @param sourcepath    source roots of the module and the modules it depends on, so types not compiled yet still
 *                      resolve
 * @param processorPath the bundled SpringGraph processor first, then the module's other processors (Lombok,
 *                      MapStruct), so generated constructors are visible
 * @param encoding      source encoding
 * @param mode          {@code advisory} or {@code strict}
 * @param boundaries    the {@code -Aspringgraph.runtimeBoundaries} value, already normalized (no whitespace)
 * @param workDir       a directory owned by the plugin; its {@code classes} and {@code generated} subdirectories are
 *                      replaced on every run
 */
public record JavacRequest(
        Path javac,
        List<Path> sources,
        List<Path> classpath,
        List<Path> sourcepath,
        List<Path> processorPath,
        String encoding,
        String mode,
        String boundaries,
        Path workDir) {

    public JavacRequest {
        sources = List.copyOf(sources);
        classpath = List.copyOf(classpath);
        sourcepath = List.copyOf(sourcepath);
        processorPath = List.copyOf(processorPath);
    }

    /** Where javac writes class-output resources, including the report. */
    public Path classOutput() {
        return workDir.resolve("classes");
    }

    /** Where javac writes sources generated by other processors (MapStruct). */
    public Path generatedSources() {
        return workDir.resolve("generated");
    }

    /** The report this run writes. */
    public Path report() {
        return classOutput().resolve("META-INF/springgraph/graph.json");
    }
}
