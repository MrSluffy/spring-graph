package io.springgraph.processor;

import io.springgraph.processor.internal.GraphAnalysis;
import io.springgraph.processor.internal.config.Options;
import io.springgraph.processor.internal.diagnostic.Code;
import io.springgraph.processor.internal.discovery.ComponentFactory;
import io.springgraph.processor.internal.discovery.SpringTypes;
import io.springgraph.processor.internal.findings.BoundaryChecker;
import io.springgraph.processor.internal.findings.ResolutionReporter;
import io.springgraph.processor.internal.report.GraphReport;
import io.springgraph.processor.internal.resolution.DependencyResolver;
import java.util.Set;
import java.util.SortedSet;
import java.util.TreeSet;
import javax.annotation.processing.AbstractProcessor;
import javax.annotation.processing.ProcessingEnvironment;
import javax.annotation.processing.RoundEnvironment;
import javax.annotation.processing.SupportedOptions;
import javax.lang.model.SourceVersion;
import javax.lang.model.element.Element;
import javax.lang.model.element.ElementKind;
import javax.lang.model.element.TypeElement;
import javax.tools.Diagnostic;

/**
 * Validation-only annotation processor. It never generates code and has no runtime footprint.
 *
 * <p>Opt-in: it does nothing unless {@code -Aspringgraph.mode=advisory|strict} is supplied.
 *
 * <p>Round handling: candidate classes are collected by name in every round, and the whole analysis
 * ({@link GraphAnalysis}) runs once in the final round, so types generated by other processors (Lombok, MapStruct) are
 * visible. No compiler objects are held across rounds.
 *
 * <p>Code map: {@link Options} (configuration), {@link ComponentFactory} (discovery), {@link DependencyResolver}
 * (resolution rules), {@link BoundaryChecker} and {@link ResolutionReporter} (findings), {@link GraphReport} (report).
 */
@SupportedOptions({SpringGraphProcessor.OPT_MODE, SpringGraphProcessor.OPT_BOUNDARIES})
public final class SpringGraphProcessor extends AbstractProcessor {

    public static final String OPT_MODE = "springgraph.mode";
    public static final String OPT_BOUNDARIES = "springgraph.runtimeBoundaries";
    public static final String REPORT_PATH = "META-INF/springgraph/graph.txt";
    /** Machine-readable report for tools; see docs/reference/report-json.md. */
    public static final String JSON_REPORT_PATH = "META-INF/springgraph/graph.json";

    /** Null when the processor is disabled or misconfigured. */
    private Options options;

    private final SortedSet<String> candidates = new TreeSet<>();

    @Override
    public synchronized void init(ProcessingEnvironment env) {
        super.init(env);
        // Parsed here so that an invalid mode is reported even when the module has no components.
        options = Options.parse(
                env.getOptions(),
                error -> env.getMessager().printMessage(Diagnostic.Kind.ERROR, Code.SG009.name() + ": " + error));
    }

    @Override
    public Set<String> getSupportedAnnotationTypes() {
        Set<String> types = new TreeSet<>(SpringTypes.STEREOTYPES);
        types.add(SpringTypes.CONFIGURATION);
        return types;
    }

    @Override
    public SourceVersion getSupportedSourceVersion() {
        return SourceVersion.latestSupported();
    }

    @Override
    public boolean process(Set<? extends TypeElement> annotations, RoundEnvironment roundEnv) {
        if (options == null) {
            return false;
        }
        for (TypeElement annotation : annotations) {
            for (Element element : roundEnv.getElementsAnnotatedWith(annotation)) {
                if (element instanceof TypeElement type && type.getKind() == ElementKind.CLASS) {
                    candidates.add(type.getQualifiedName().toString());
                }
            }
        }
        if (roundEnv.processingOver()) {
            new GraphAnalysis(processingEnv, options).run(candidates);
        }
        return false; // never claim Spring's annotations; other processors may need them
    }
}
